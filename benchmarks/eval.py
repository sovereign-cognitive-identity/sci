#!/usr/bin/env python3
"""SCI-291/292 evaluator: real metrics for sci-anonymizer.

Reads corpus-index.jsonl, runs each doc through the Rust bench-harness
(which calls sci-anonymizer), and computes:
  - per-entity-type precision/recall/F1 vs gold labels
  - round-trip fidelity (anonymize -> deanonymize == original)

Entity matching is type + text-overlap (a detected entity matches a gold
entity of the same type when either text contains the other) — tolerant of
boundary differences like surrounding quotes or a leading '+'.
"""
import json
import subprocess
import sys
from pathlib import Path
from collections import defaultdict

HERE = Path(__file__).resolve().parent
CORPUS = HERE / "corpus" / "corpus-index.jsonl"
HARNESS = HERE / "target" / "release" / "bench-harness"
RESULTS = HERE / "RESULTS.md"
TYPES = ["PERSON", "ORG", "PLACE", "EMAIL", "PHONE", "URL", "HANDLE"]


def overlaps(a: str, b: str) -> bool:
    a, b = a.strip().lower(), b.strip().lower()
    return a in b or b in a


def main() -> int:
    docs = [json.loads(l) for l in CORPUS.read_text().splitlines() if l.strip()]
    texts = "\n".join(d["text"] for d in docs).encode()
    out = subprocess.run([str(HARNESS)], input=texts, capture_output=True, check=True)
    runs = [json.loads(l) for l in out.stdout.decode().splitlines() if l.strip()]

    tp = defaultdict(int); fp = defaultdict(int); fn = defaultdict(int)
    fidelity_sum = 0.0
    for doc, run in zip(docs, runs):
        fidelity_sum += run["fidelity"]
        gold = [(e["type"], e["text"]) for e in doc.get("entities", [])]
        det = [(e["entity_type"], e["text"]) for e in run.get("entities", [])]
        gold_used = [False] * len(gold)
        for dt, dtext in det:
            hit = next((i for i, (gt, gx) in enumerate(gold)
                        if not gold_used[i] and gt == dt and overlaps(dtext, gx)), None)
            if hit is None:
                fp[dt] += 1
            else:
                gold_used[hit] = True
                tp[dt] += 1
        for i, (gt, _) in enumerate(gold):
            if not gold_used[i]:
                fn[gt] += 1

    def prf(t):
        p = tp[t] / (tp[t] + fp[t]) if (tp[t] + fp[t]) else 0.0
        r = tp[t] / (tp[t] + fn[t]) if (tp[t] + fn[t]) else 0.0
        f = 2 * p * r / (p + r) if (p + r) else 0.0
        return p, r, f

    TP = sum(tp.values()); FP = sum(fp.values()); FN = sum(fn.values())
    P = TP / (TP + FP) if (TP + FP) else 0.0
    R = TP / (TP + FN) if (TP + FN) else 0.0
    F1 = 2 * P * R / (P + R) if (P + R) else 0.0
    fidelity = fidelity_sum / len(docs) if docs else 0.0

    rows = []
    for t in TYPES:
        present = tp[t] + fp[t] + fn[t]
        if not present:
            rows.append(f"| {t} | 0 | 0 | 0 | — | — | — | not present in corpus |")
            continue
        p, r, f = prf(t)
        rows.append(f"| {t} | {tp[t]} | {fp[t]} | {fn[t]} | {p:.2f} | {r:.2f} | {f:.2f} | |")

    md = f"""# SCI-273 Benchmark Results

_Generated by `benchmarks/eval.py` (run `bash run.sh` to regenerate)._

## Corpus

| Source | Count | Status |
|--------|-------|--------|
| CoNLL-2003 NER | ~1,000 docs | **not loaded** — requires `pip install datasets` (see `corpus-builder.py`) |
| SCI-195/196/197 edge cases | {len(docs)} docs | loaded |
| **Total evaluated** | **{len(docs)} docs** | |

> ⚠️ These numbers are measured on the {len(docs)}-doc edge-case corpus only.
> The public CoNLL set is not yet wired in, so per-type recall here is **not**
> representative of real-world performance — especially PERSON, which relies on
> the capitalized/camelCase heuristic + custom-entity DB (no Rust NLP NER yet;
> tracked in SCI-123). Treat this as a reproducible harness with honest small-N
> results, not a headline benchmark.

## Results: sci-anonymizer

| Metric | Value |
|--------|-------|
| Precision | {P:.2f} |
| Recall | {R:.2f} |
| F1 | {F1:.2f} |
| Round-trip fidelity | {fidelity:.2f} |

### Per-entity-type

| Type | TP | FP | FN | Precision | Recall | F1 | Notes |
|------|----|----|----|-----------|--------|----|-------|
{chr(10).join(rows)}

## Round-trip fidelity

**{fidelity:.2f}** across {len(docs)} docs (anonymize → deanonymize == original).
This is the metric Presidio cannot score — it performs destructive one-way
redaction, so there is nothing to reverse.

## Presidio comparison

Presidio is **not run here** (kept dependency-isolated). To produce a
head-to-head column locally:

```bash
cd benchmarks/presidio
pip install presidio-analyzer presidio-anonymizer -q
python3 runner.py --corpus ../corpus/corpus-index.jsonl
```

## Reproduce

```bash
cd benchmarks && bash run.sh
```
"""
    RESULTS.write_text(md)
    print(f"Wrote {RESULTS} — {len(docs)} docs, P={P:.2f} R={R:.2f} F1={F1:.2f} fidelity={fidelity:.2f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
